/**
 * The code shown on the book's <a
 * href="https://higher-kinded-j.github.io/latest/monads/eitherf.html">EitherF</a> page: one program
 * that uses two instruction sets, {@link OrderOp} and {@link NoticeOp}, joined by {@code EitherF};
 * an interpreter for each, combined into one; a program written for {@code OrderOp} alone moved
 * into the pair; and the same pair generated by {@code @ComposeEffects}. The page {@code
 * {{#include}}}s the anchored regions, {@code EitherFBookTest} holds the claims the page makes, and
 * the book's output gate runs {@link #main} against the comments in the regions.
 */
public final class EitherFBook {

  static final UUID ORDER = UUID.fromString("00000000-0000-0000-0000-000000000042");
  static final BigDecimal LIMIT = new BigDecimal("30.00");
  static final Map<String, BigDecimal> CATALOGUE =
      Map.of("LAMP", new BigDecimal("40.00"), "BULB", new BigDecimal("2.50"));

  private EitherFBook() {}

  // ANCHOR: wiring
  // The pair's Functor maps an instruction from either set
  static final EitherFFunctor<OrderOpKind.Witness, NoticeOpKind.Witness> ORDERS_AND_NOTICES =
      OrderEffectsSupport.functor(OrderOpFunctor.instance(), NoticeOpFunctor.instance());

  // Each set's generated constructors, bound to its side of the pair
  static final OrderOpOps.Bound<EitherFKind.Witness<OrderOpKind.Witness, NoticeOpKind.Witness>>
      ORDERS = OrderOpOps.boundTo(OrderEffectsSupport.injectOrders(), ORDERS_AND_NOTICES);
  static final NoticeOpOps.Bound<EitherFKind.Witness<OrderOpKind.Witness, NoticeOpKind.Witness>>
      NOTICES = NoticeOpOps.boundTo(OrderEffectsSupport.injectNotices(), ORDERS_AND_NOTICES);

  // ANCHOR_END: wiring

  // ANCHOR: by_hand
  // What OrderEffectsSupport's two Injects are: orders go on the left, notices on the right
  @SuppressWarnings("migration-nudge") // shows what @ComposeEffects generates
  static final Inject<
          OrderOpKind.Witness, EitherFKind.Witness<OrderOpKind.Witness, NoticeOpKind.Witness>>
      INTO_ORDERS = InjectInstances.injectLeft();

  @SuppressWarnings("migration-nudge") // shows what @ComposeEffects generates
  static final Inject<
          NoticeOpKind.Witness, EitherFKind.Witness<OrderOpKind.Witness, NoticeOpKind.Witness>>
      INTO_NOTICES = InjectInstances.injectRight();

  // ANCHOR_END: by_hand

  // ANCHOR: program
  // Cancels the order if the line costs more than the limit, and tells the customer why
  static FreePath<EitherFKind.Witness<OrderOpKind.Witness, NoticeOpKind.Witness>, Boolean>
      cancelAndTell(UUID orderId, String sku, BigDecimal limit) {
    return Path.free(ORDERS.priceOf(sku, Function.identity()), ORDERS_AND_NOTICES)
        .via(
            price ->
                price.compareTo(limit) <= 0
                    ? Path.freePure(false, ORDERS_AND_NOTICES)
                    : Path.free(ORDERS.cancel(orderId, Function.identity()), ORDERS_AND_NOTICES)
                        .then(
                            () ->
                                Path.free(
                                    NOTICES.send(
                                        orderId,
                                        "Cancelled: " + sku + " costs " + price,
                                        Function.identity()),
                                    ORDERS_AND_NOTICES))
                        .map(_ -> true));
  }

  // ANCHOR_END: program

  // ANCHOR: interpreters
  // Runs each order instruction against a catalogue and a list of cancelled orders
  static final class InMemoryOrders extends OrderOpInterpreter<IdKind.Witness> {
    final List<UUID> cancelled = new ArrayList<>();

    @Override
    protected <A> Kind<IdKind.Witness, A> handlePriceOf(OrderOp.PriceOf<A> op) {
      return ID.widen(Id.of(op.k().apply(CATALOGUE.get(op.sku()))));
    }

    @Override
    protected <A> Kind<IdKind.Witness, A> handleCancel(OrderOp.Cancel<A> op) {
      cancelled.add(op.orderId());
      return ID.widen(Id.of(op.k().apply(Unit.INSTANCE)));
    }
  }

  // Keeps each notice in an outbox instead of sending it
  static final class Outbox extends NoticeOpInterpreter<IdKind.Witness> {
    final List<String> sent = new ArrayList<>();

    @Override
    protected <A> Kind<IdKind.Witness, A> handleSend(NoticeOp.Send<A> op) {
      sent.add(op.text());
      return ID.widen(Id.of(op.k().apply(Unit.INSTANCE)));
    }
  }

  // ANCHOR_END: interpreters

  public static void main(String[] args) {
    // ANCHOR: run
    InMemoryOrders orders = new InMemoryOrders();
    Outbox outbox = new Outbox();

    // One interpreter for the pair: each instruction goes to the one for its set
    Natural<EitherFKind.Witness<OrderOpKind.Witness, NoticeOpKind.Witness>, IdKind.Witness> both =
        Interpreters.combine(orders, outbox);

    boolean cancelled =
        ID.narrow(
                cancelAndTell(ORDER, "LAMP", LIMIT).foldMap(both, Instances.monad(id())).runKind())
            .value();
    // true

    List<String> notices = outbox.sent;
    // [Cancelled: LAMP costs 40.00]
    // ANCHOR_END: run
    System.out.println(cancelled);
    System.out.println(notices);

    // ANCHOR: translate
    // Written for OrderOp alone, before notices existed
    FreePath<OrderOpKind.Witness, BigDecimal> lampAndBulb =
        Path.free(OrderOpOps.priceOf("LAMP", Function.identity()), OrderOpFunctor.instance())
            .zipWith(
                Path.free(
                    OrderOpOps.priceOf("BULB", Function.identity()), OrderOpFunctor.instance()),
                BigDecimal::add);

    // Each instruction moves to the left of the pair; the program is otherwise unchanged
    Free<EitherFKind.Witness<OrderOpKind.Witness, NoticeOpKind.Witness>, BigDecimal> joined =
        Free.translate(lampAndBulb.toFree(), INTO_ORDERS::inject, ORDERS_AND_NOTICES);

    BigDecimal total =
        ID.narrow(
                joined.foldMap(
                    Interpreters.combine(new InMemoryOrders(), new Outbox()),
                    Instances.monad(id())))
            .value();
    // 42.50
    // ANCHOR_END: translate
    System.out.println(total);

    // ANCHOR: by_kind
    // An instruction in the pair is an EitherF: Left holds an order instruction, Right a notice
    EitherF<OrderOpKind.Witness, NoticeOpKind.Witness, Unit> held =
        EITHERF.narrow(
            INTO_NOTICES.inject(
                NOTICE_OP.widen(new NoticeOp.Send<>(ORDER, "Shipped", Function.identity()))));

    // fold acts on whichever side holds the instruction
    boolean aNotice = held.fold(_ -> false, _ -> true);
    // true
    // ANCHOR_END: by_kind
    System.out.println(aNotice);
  }
}
